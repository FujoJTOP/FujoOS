/// 写 backbuffer 像素 (整数拆色, 下采样防越界)。
fn set_pixel(x: u32, y: u32, col: u32) {
    if x >= fb_w() || y >= fb_h() {
        return;
    }
    unsafe {
        let p = (BACKBUFFER + ((y as u64) * fb_w() as u64 + x as u64) * 4) as *mut u32;
        p.write(col);
    }
}

fn read_pixel(x: u32, y: u32) -> u32 {
    if x >= fb_w() || y >= fb_h() {
        return 0;
    }
    unsafe {
        let p = (BACKBUFFER + ((y as u64) * fb_w() as u64 + x as u64) * 4) as *const u32;
        p.read()
    }
}

/// M39: 画前景字符带背景 (缩放+超采样 AA 由本函数完成)。
/// 字形: 每字符 5 字节 = 5 行, 每字节低 5 bit = 5 列 (bit4=最左列)。
fn draw_char(x: u32, y: u32, ch: u8, scale: u32, color: u32) {
    if ch < 0x20 {
        return;
    }
    let g = GLYPHS[(ch - 0x20) as usize];
    for gy in 0..5u32 {
        for gx in 0..5u32 {
            let on = (g[gy as usize] >> (4 - gx)) & 1 != 0;
            for sy in 0..scale {
                for sx in 0..scale {
                    let px = x + gx * scale + sx;
                    let py = y + gy * scale + sy;
                    if on {
                        set_pixel(px, py, color);
                    }
                }
            }
        }
    }
}

/// 0x5601: 文本渲染 (x, y, scale 1..=4, color, str ptr) -> 字符数。
pub fn fujo_font_text(x: u64, y: u64, scale: u64, color: u64, strp: u64) -> i64 {
    let scale = (scale.clamp(1, 4) + crate::a11y::scale_boost() as u64) as u32;
    let mut cx = x as u32;
    let mut n = 0i64;
    loop {
        let b = unsafe { (strp as *const u8).add(n as usize).read() };
        if b == 0 {
            break;
        }
        draw_char(cx, y as u32, b, scale, color as u32);
        cx += (8 * scale) as u32;
        n += 1;
    }
    serial::write_str("font : draw_text \"");
    // 打印 (简单: 已画)
    serial::write_line("\"");
    n
}

/// 0x5602: 读回 backbuffer 像素 (验证)。
pub fn fujo_font_pixel(x: u64, y: u64) -> i64 {
    read_pixel(x as u32, y as u32) as i64
}

/// 0x5603: 清屏 (backbuffer 填色) — 供验证前清底。
pub fn fujo_font_clear(color: u64) -> i64 {
    let g = (color as u32) & 0x00FF_FFFF;
    let dark = 0xFF000000u32 | g;
    unsafe {
        for y in 0..fb_h() {
            for x in 0..fb_w() {
                let p = (BACKBUFFER + ((y as u64) * fb_w() as u64 + x as u64) * 4) as *mut u32;
                p.write(dark);
            }
        }
    }
    0
}
