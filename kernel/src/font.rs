//! font.rs — 位图字体系统 (M39): 5x7 全 ASCII 字形 + 缩放 + 超采样抗锯齿
//!
//! 字形: 0x20..0x7F (96 字符), 5 列 × 7 行, 每字符 5 字节 (bit4..bit0 = 列 4..0)。
//! 渲染: draw_char(x, y, ch, scale, color, bg) -> RAM backbuffer (0xC00000, 3MiB);
//!   AA: 每输出像素 = scale² 个子像素均分 (整数超采样, 16 级灰度边缘)。
//! 用户原语: 0x5601 font_text(x, y, scale, color, str)
//!           0x5602 font_pixel(x, y) -> 读回 backbuffer 像素 (验证)

use crate::serial;

pub const BACKBUFFER: u64 = 0xC00000; // RAM 双缓冲 (M4 graphics backbuffer)
/// M47: 当前分辨率 (vbe_set_mode 动态调整)。
